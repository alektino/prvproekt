NOT_CITY = r"БЕТ\. СТОЛБ"


def settlement_of(addr):
    a = re.sub(r"\s+", " ", addr.upper())
    for pat, name, conf in RULES:
        if re.search(pat, a):
            return name, conf
    if a.startswith("КИЧЕВО") and not re.search(NOT_CITY, a):
        return "Кичево (град)", "средна" if "БИЧИНЦИ" in a else "висока"
    return "", "непознато населено место"


def write(name, rows, fields):
    with open(DATA / name, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader(); w.writerows(rows)


def main(lamps_xlsx, places_xlsx):
    places = read_places(places_xlsx)
    known = {p["settlement"] for p in places}
    group_of = {p["settlement"]: p["group"] for p in places}
    lamps = read_lamps(lamps_xlsx, places)
    write("naseleni.csv", places, ["settlement", "group", "area_km2", "unit"])
    write("svetilki.csv", lamps, ["group", "settlement", "unit", "lamp_list_name", "street", "manufacturer", "watt", "count"])

    last = {}
    for r in csv.DictReader(open(DATA / "stavki.csv", encoding="utf-8")):
        if "LV1" in r["category"]:
            last[r["meter"]] = r["address"].strip()
    rows = []
    for meter, addr in sorted(last.items(), key=lambda x: x[1]):
        name, conf = settlement_of(addr)
        if name and name not in known:
            raise SystemExit(f"Непознато населено место во правилата: {name}")
        rows.append({"meter": meter, "address": addr, "settlement": name, "unit": unit_of(name) if name else "",
                     "group": group_of.get(name, ""), "certainty": conf})
    write("mapiranje.csv", rows, ["meter", "address", "settlement", "unit", "group", "certainty"])
    print(len(places), "населени места,", len({p["unit"] for p in places}), "единици;",
          sum(l["count"] for l in lamps), "светилки;", len(rows), "мерни места,", sum(1 for r in rows if r["settlement"]), "поврзани")


