def read_places(path):
    ws = openpyxl.load_workbook(path, data_only=True)["Населени места"]
    out = []
    for row in ws.iter_rows(values_only=True):
        rb, name, group, area = (list(row) + [None] * 4)[:4]
        if isinstance(rb, int) and name and group:
            out.append({"settlement": name.strip(), "group": group.strip(), "area_km2": area, "unit": unit_of(name.strip())})
    return out


def read_lamps(path, places):
    known = {p["settlement"] for p in places}
    group_of = {p["settlement"]: p["group"] for p in places}
    ws = openpyxl.load_workbook(path, data_only=True).active
    out, in_city = [], False
    for row in ws.iter_rows(values_only=True):
        a, b, c, d, e, f = (list(row) + [None] * 6)[:6]
        if isinstance(b, str) and "Општина" in b and c is None:
            in_city = "Градот" in b
            continue
        if isinstance(a, int) and c == "ЛЕД Светилка" and isinstance(e, (int, float)):
            raw = re.sub(r"^[\s ]+|[\s :]+$", "", b)
            name = "Кичево (град)" if in_city else LAMP_NAMES.get(raw, raw)
            if name not in known:
                raise SystemExit(f"Населеното место од списокот на светилки го нема во службениот список: {raw}")
            out.append({"group": group_of[name], "settlement": name, "unit": unit_of(name), "lamp_list_name": raw,
                        "street": raw if in_city else "", "manufacturer": d, "watt": e, "count": f})
    return out


